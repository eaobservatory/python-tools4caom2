#!/usr/bin/env python3

import os
import pprint
import sys

from cadcutils.net.ws import get_resources

TAP = 'ivo://ivoa.net/std/TAP'
PROXY = 'ivo://ivoa.net/sso#tls-with-certificate'

# List of capability, security method and name for each resource required.
services = {
    'ivo://cadc.nrc.ca/cred': (
        'ivo://ivoa.net/std/CDP#proxy-1.0',
        'ivo://ivoa.net/sso#BasicAA',
        'cred',
    ),
    'ivo://cadc.nrc.ca/argus': (
        TAP,
        PROXY,
        'argus',
    ),
    'ivo://cadc.nrc.ca/ams/eao': (
        TAP,
        PROXY,
        'ams/eao',
    ),
    'ivo://cadc.nrc.ca/cadc/minoc': (
        'http://www.opencadc.org/std/storage#files-1.0',
        PROXY,
        'minoc',
    ),
    'ivo://cadc.nrc.ca/cadc/luskan': (
        TAP,
        PROXY,
        'luskan',
    ),
    'ivo://cadc.nrc.ca/ums': (
        'ivo://ivoa.net/sso#tls-with-password',
        None,
        'ac',
    ),
}


resources = get_resources()

info = {
    services[resource][2]: caps.get_access_url(
        services[resource][0],
        ([] if services[resource][1] is None else [services[resource][1]]))
    for (resource, url, caps) in resources
    if resource in services
}

formatted = pprint.pformat(info, indent=4, sort_dicts=True)
if formatted.startswith('{'):
    formatted = '{\n ' + formatted[1:]

with open('lib/tools4caom2/resources.py', 'w') as f:
    f.write('# Resources list auto-generated by {}\n\n'.format(
        os.path.basename(sys.argv[0])))
    f.write('resources = {}'.format(
        formatted))
